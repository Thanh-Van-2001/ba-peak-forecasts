"""Every number in the paper. Reads out/results.json and out/ba_table.csv; writes paper/macros.tex,
paper/tab_robust.tex and out/macros.json. Run from the repository root: python -I code/make_macros.py"""
import json

import numpy as np
import pandas as pd
from scipy import stats

R = json.load(open("out/results.json"))
T = pd.read_csv("out/ba_table.csv", index_col=0)
P = T[T["primary"]]
H, S, RB, D = R["hypotheses"], R["secondary"], R["robustness"], R["descriptive"]
M = {}


def f(x, d=2):
    s = f"{x:.{d}f}"
    return s.replace("-", "$-$") if s.startswith("-") else s


def pvt(p):
    return "$<$0.001" if p < 0.001 else f"{p:.3f}" if p < 0.01 else f"{p:.2f}"


def pv(p):
    """Relation form for use as $p\res{key}$."""
    return "<0.001" if p < 0.001 else "=" + (f"{p:.3f}" if p < 0.01 else f"{p:.2f}")


M["nPrimary"], M["nEligible"] = str(D["n_primary"]), str(D["n_eligible"])
M["nDaysK"] = f(P["days"].sum() / 1e3, 0)
M["medDays"] = str(int(P["days"].median()))
for k, tag in (("H1", "One"), ("H2", "Two"), ("H3", "Three"), ("H4", "Four")):
    h = H[k]
    M[f"h{tag}Neg"], M[f"h{tag}N"], M[f"h{tag}P"], M[f"h{tag}Holm"] = str(h["neg"]), str(h["n"]), pv(h["p"]), pv(h["p_holm"])
    M[f"h{tag}Pos"] = str(h["n"] - h["neg"])
for k, tag in (("pooled_A", "A"), ("pooled_F", "F"), ("pooled_heat", "Heat"), ("pooled_trend", "Trend")):
    q = S[k]
    M[f"pool{tag}"], M[f"pool{tag}Lo"], M[f"pool{tag}Hi"] = f(q["mu"]), f(q["lo"]), f(q["hi"])
    M[f"pool{tag}I"] = f(100 * q["I2"], 0)
M["medBiasAll"], M["medBiasA"], M["medBiasF"] = f(D["median_bias_all"]), f(D["median_bias_A"]), f(D["median_bias_F"])
M["medNullA"] = f(D["median_null_bias_A"])
M["belowNull"] = str(D["below_null"])
M["shareLowPooled"], M["shareLowMed"] = f(100 * D["pooled_share_low_days"], 0), f(100 * D["median_share_low"], 0)
M["medNullF"] = f(P["null_bias_F"].median())
# exploratory: conditional bias relative to each BA's overall bias
exA, exF = P["bias_A"] - P["bias_all"], P["bias_F"] - P["bias_all"]
M["exANeg"], M["exFPos"] = str(int((exA < 0).sum())), str(int((exF > 0).sum()))
M["exAMed"], M["exFMed"] = f(exA.median()), f(exF.median())
M["exFP"] = pv(stats.binomtest(int((exF > 0).sum()), int((exF != 0).sum()), 0.5).pvalue)
lev = P[P["bias_all"].abs() > 10]
M["nLevel"], M["levelBas"] = str(len(lev)), " and ".join(lev.index)
M["levelMin"], M["levelMax"] = f(lev["bias_all"].abs().min(), 0), f(lev["bias_all"].abs().max(), 0)
Q = P[P["bias_all"].abs() <= 10]
M["exclHOneNeg"], M["exclHTwoNeg"], M["exclN"] = str(int((Q["bias_A"] < 0).sum())), str(int((Q["bias_F"] < 0).sum())), str(len(Q))
# MZ
M["mzAbove"], M["mzAboveSig"], M["mzBelowSig"] = str(RB["mz_above1"]), str(RB["mz_above1_sig"]), str(RB["mz_below1_sig"])
M["mzMed"] = f(P["mz_slope"].median())
# heat
M["hotThrMed"] = f(P["hot_thr_c"].median(), 1)
M["hotThrMin"], M["hotThrMax"] = f(P["hot_thr_c"].min(), 1), f(P["hot_thr_c"].max(), 1)
M["nHotMed"] = str(int(P["n_hot"].median()))
M["heatMed"] = f(P["heat"].median())
M["otherMed"] = f(P["heat_other"].median())
for k, tag in (("run1", "One"), ("run2", "Two"), ("run3", "Three")):
    M[f"run{tag}"] = f(P[f"heat_{k}"].median())
    M[f"nRun{tag}"] = str(int(P[f"n_{k}"].sum()))
M["runThreePos"] = str(int((P["heat_run3"] > 0).sum()))
M["runOneNeg"] = str(int((P["heat_run1"] < 0).sum()))
M["trendMed"] = f(P["trend"].median())
M["mapeMed"] = f(P["mape"].median())
# robustness table
rows = []
lab = {"main": "Primary (5\\% days, $p_d$)", "secondary": "All eligible BAs", "top10": "Top 10\\% days",
       "peakhour": "Peak-hour error $e_d$", "adjusted": "EIA adjusted demand", "region": "EIA regions (one vote each)"}
for k in ("secondary", "top10", "peakhour", "adjusted", "region"):
    a, b = RB[f"{k}_H1"], RB[f"{k}_H2"]
    rows.append(f"{lab[k]} & {a['neg']}/{a['n']} & {pvt(a['p'])} & {b['neg']}/{b['n']} & {pvt(b['p'])} \\\\")
a, b = H["H1"], H["H2"]
rows.insert(0, f"{lab['main']} & {a['neg']}/{a['n']} & {pvt(a['p'])} & {b['neg']}/{b['n']} & {pvt(b['p'])} \\\\")
open("paper/tab_robust.tex", "w", encoding="utf-8").write("\n".join(rows) + "\n")
for k in ("secondary", "top10", "peakhour", "region"):
    M[f"rob{k.capitalize()}OneNeg"], M[f"rob{k.capitalize()}OneN"] = str(RB[f"{k}_H1"]["neg"]), str(RB[f"{k}_H1"]["n"])
    M[f"rob{k.capitalize()}OneP"] = pv(RB[f"{k}_H1"]["p"])

with open("paper/macros.tex", "w", encoding="utf-8") as fh:
    fh.write("% generated by code/make_macros.py -- do not edit\n\\makeatletter\n")
    for k, v in sorted(M.items()):
        fh.write(f"\\expandafter\\def\\csname res@{k}\\endcsname{{{v}}}\n")
    fh.write("\\makeatother\n\\newcommand{\\res}[1]{\\ifcsname res@#1\\endcsname\\csname res@#1\\endcsname\\else\\textbf{??#1??}\\fi}\n")
json.dump(M, open("out/macros.json", "w"), indent=0)
print(len(M), "macros")
print({k: M[k] for k in ("exANeg", "exFPos", "exFP", "exAMed", "exFMed", "levelBas", "exclHOneNeg", "exclHTwoNeg", "exclN", "nDaysK", "hotThrMed", "runThreePos", "runOneNeg", "mzMed")})

# ---- amendment 1 (exploratory analyses added after the results; see PLAN.md) ----
X = R["exploratory"]
M2 = {}
M2["shareNegPooled"], M2["shareNegMed"] = f(100 * X["share_pneg_pooled"], 0), f(100 * X["share_pneg_median"], 0)
M2["ptwoOneNeg"], M2["ptwoTwoNeg"] = str(X["p2_H1"]["neg"]), str(X["p2_H2"]["neg"])
M2["relFPos"], M2["relFP"] = str(X["rel_F"]["neg"]), pv(X["rel_F"]["p"])
M2["relANeg"], M2["relAP"] = str(X["rel_A"]["neg"]), pv(X["rel_A"]["p"])
M2["belowNullMonth"], M2["medNullMonth"] = str(X["below_null_month"]), f(X["median_null_month"])
M2["mzrBelowSig"], M2["mzrAboveSig"], M2["mzrMed"] = str(X["mzr_below1_sig"]), str(X["mzr_above1_sig"]), f(X["mzr_median"])
M2["heatLagNeg"], M2["heatLagP"], M2["heatLagMed"] = str(X["heat_lag"]["neg"]), pv(X["heat_lag"]["p"]), f(X["heat_lag_median"])
M2["runOneOtherNeg"], M2["runOneOtherP"] = str(X["run1_vs_other"]["neg"]), pv(X["run1_vs_other"]["p"])
M2["runThreeOtherNeg"], M2["runThreeOtherP"] = str(X["run3_vs_other"]["n"] - X["run3_vs_other"]["neg"]), pv(X["run3_vs_other"]["p"])
M2["spellNeg"], M2["spellN"], M2["spellP"] = str(X["spell_d1_vs_d3"]["neg"]), str(X["spell_d1_vs_d3"]["n"]), pv(X["spell_d1_vs_d3"]["p"])
M2["spellMed"] = f(X["spell_d1_minus_d3_median"])
M2["nHotMin"], M2["nHotMax"] = str(X["n_hot_min"]), str(X["n_hot_max"])
for k, tag in (("pooled_A_excl", "AEx"), ("pooled_F_excl", "FEx"), ("pooled_heat_excl", "HeatEx")):
    q = X[k]
    M2[f"pool{tag}"], M2[f"pool{tag}Lo"], M2[f"pool{tag}Hi"] = f(q["mu"]), f(q["lo"]), f(q["hi"])
M2["adjEqual"] = str(X["adj_equal_A"])
M2["nFgtA"] = str(int((P["bias_F"] > P["bias_A"]).sum()))
M2["regionTwoNeg"], M2["regionTwoN"] = str(RB["region_H2"]["neg"]), str(RB["region_H2"]["n"])
M2["nRunOneDays"] = str(int(P["n_run1"].sum()))
M2["nRunTwoDays"], M2["nRunThreeDays"] = str(int(P["n_run2"].sum())), str(int(P["n_run3"].sum()))
M.update(M2)
a, b = X["p2_H1"], X["p2_H2"]
with open("paper/tab_robust.tex", "a", encoding="utf-8") as fh:
    fh.write(f"Second-highest hour$^\\dagger$ & {a['neg']}/{a['n']} & {pvt(a['p'])} & {b['neg']}/{b['n']} & {pvt(b['p'])} \\\\\n")
with open("paper/macros.tex", "w", encoding="utf-8") as fh:
    fh.write("% generated by code/make_macros.py -- do not edit\n\\makeatletter\n")
    for k, v in sorted(M.items()):
        fh.write(f"\\expandafter\\def\\csname res@{k}\\endcsname{{{v}}}\n")
    fh.write("\\makeatother\n\\newcommand{\\res}[1]{\\ifcsname res@#1\\endcsname\\csname res@#1\\endcsname\\else\\textbf{??#1??}\\fi}\n")
json.dump(M, open("out/macros.json", "w"), indent=0)
print(len(M), "macros incl. amendment 1")

# ---- amendment 2 (exploratory, after independent review; see PLAN.md and code/amendment2.py) ----
Z = json.load(open("out/amendment2.json"))
M3 = {}
B = Z["bounds"]
for k, tag in (("bias_A", "A"), ("bias_F", "F"), ("heat", "Heat")):
    b = B[k]
    M3[f"share{tag}Neg"] = f(100 * b["neg"] / b["n"], 0)
    M3[f"share{tag}CpLo"], M3[f"share{tag}CpHi"] = f(100 * b["cp_share_ci"][0], 0), f(100 * b["cp_share_ci"][1], 0)
    for u, ut in (("region", "Reg"), ("ba", "Ba")):
        M3[f"med{tag}{ut}Lo"], M3[f"med{tag}{ut}Hi"] = f(b[u]["median_ci"][0]), f(b[u]["median_ci"][1])
        M3[f"share{tag}{ut}Lo"], M3[f"share{tag}{ut}Hi"] = f(100 * b[u]["share_ci"][0], 0), f(100 * b[u]["share_ci"][1], 0)
M3["nRegions"] = str(Z["n_regions"])
M3["sigFBelow"], M3["sigFAbove"] = str(Z["bias_F_sig_below"]), str(Z["bias_F_sig_above"])
# claims stated in words in the paper
assert (P.loc[Z["bias_F_sig_below_bas"], "bias_all"] < 0).all(), "text: all with a negative bias over all days"
assert X["pooled_F_excl"]["lo"] > 0, "text: pooled bias_F without the level-gap BAs is above zero"
assert Z["region_H3"]["p"] >= 0.05 and Z["region_run1"]["p"] < 0.05 and RB["region_H1"]["p"] >= 0.05, "text: regional results"
assert B["bias_A"]["region"]["median_ci"][1] < 0, "text: regional bootstrap places median bias_A below zero"
assert B["heat"]["region"]["median_ci"][1] > 0, "text: regional bootstrap interval for the heat difference includes zero"
for k, tag in (("region_H3", "regionThree"), ("region_run1", "regionRun")):
    M3[f"{tag}Neg"], M3[f"{tag}N"], M3[f"{tag}P"] = str(Z[k]["neg"]), str(Z[k]["n"]), pv(Z[k]["p"])
E = Z["excl_level"]
assert " and ".join(E["bas"]) == M["levelBas"]
for k, tag in (("H1", "One"), ("H2", "Two"), ("H3", "Three")):
    M3[f"exclH{tag}Neg"], M3[f"exclH{tag}N"], M3[f"exclH{tag}P"] = str(E[k]["neg"]), str(E[k]["n"]), pv(E[k]["p"])
M3["meanOneNeg"], M3["meanOneP"] = str(Z["mean_H1"]["neg"]), pv(Z["mean_H1"]["p"])
M3["meanTwoNeg"], M3["meanTwoP"] = str(Z["mean_H2"]["neg"]), pv(Z["mean_H2"]["p"])
M3["meanFMed"] = f(Z["mean_q_F_median"])
M3["belowNullLevel"], M3["medNullLevel"] = str(Z["below_null_level"]), f(Z["median_null_level"])
M.update(M3)
a, b = Z["mean_H1"], Z["mean_H2"]
with open("paper/tab_robust.tex", "a", encoding="utf-8") as fh:
    fh.write(f"Mean error, \\% of $F^*_d$$^\\ddagger$ & {a['neg']}/{a['n']} & {pvt(a['p'])} & {b['neg']}/{b['n']} & {pvt(b['p'])} \\\\\n")
with open("paper/macros.tex", "w", encoding="utf-8") as fh:
    fh.write("% generated by code/make_macros.py -- do not edit\n\\makeatletter\n")
    for k, v in sorted(M.items()):
        fh.write(f"\\expandafter\\def\\csname res@{k}\\endcsname{{{v}}}\n")
    fh.write("\\makeatother\n\\newcommand{\\res}[1]{\\ifcsname res@#1\\endcsname\\csname res@#1\\endcsname\\else\\textbf{??#1??}\\fi}\n")
json.dump(M, open("out/macros.json", "w"), indent=0)
print(len(M), "macros incl. amendment 2")
print(M3)
